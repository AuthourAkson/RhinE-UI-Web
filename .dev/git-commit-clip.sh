修复标签最后一个字母被裁掉：CalcTextWidth 的框宽要容得下字形墨迹

用户实测：某些文字末尾被裁掉一小块，例如开场动画 "SESSION AUTHORIZED" 的末字 d、
档案视图货架分组名 "UNKNOWN" 的末字 n；每种语言下固定这几处都有。

量出来的机制（面板内直接测，单位 px）：
  "UNKNOWN"              位图宽 66  末字墨迹右缘 67.7  → 超出 1.7 ✗
  "SESSION AUTHORIZED"   位图宽 426 末字墨迹右缘 429.0 → 超出 3.0 ✗
  "SHELF "               位图宽 36  末字墨迹右缘 33.3  → -2.7 ✓
  "18:17:56"（时钟）      位图宽 77  末字墨迹右缘 76.2  → -0.8 ✓
逐字形：U[步进 7.8 / 墨迹右 10.0] N[7.8 / 10.0] … 每个字形都是墨迹超出步进。

为什么墨迹会超出步进：这些标签用的是**斜体**（如货架分组名），而主题的 GeistMono 只有正体，
浏览器会**合成斜体**（把正体向右倾斜）→ 墨迹右缘跑到步进之外。主题的 labelBitmap 是逐字形
画进一张位图（每个字形用 adv[i] + dp(4) 的框），位图总宽 = Σ步进 + 字距 —— 最后一个字形
没有那个 +4 的余量，超出的部分就被裁掉了。

修法：CalcTextWidth(text, font, fromZero=true) 取 **步进与墨迹右缘的较大者**
（= DirectWrite 的 fromZero 语义，原版截图里同样的斜体字也确实没被裁、且字距本来就是松的）：
  · 取步进 → 等宽字体窄字形（冒号）推进正确，时钟不会挤在一起；
  · 取墨迹右缘 → 斜体墨迹不会越出位图。
两者取大既保住推进、又保证框容得下墨迹。

修复后实测：
  "UNKNOWN" 位图宽 81 ≥ 墨迹 80.9（-0.1 ✓）  "SESSION AUTHORIZED" 486 = 486（0.0 ✓）
  时钟 "18:17:56" 77 ≥ 76.2（-0.8 ✓，不受影响）
  逐字形变成 [步进 10.0 / 墨迹右 10.0]（不再超出）
放大 6 倍截图核对：英文 UNKNOWN 的末字 N 完整且保持斜体（与原版 AMBIENT · ELEC. 一致）；
开场 SESSION AUTHORIZED 的末字 D 完整。
MSG
