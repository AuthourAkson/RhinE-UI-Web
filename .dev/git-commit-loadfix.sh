由此修正了我之前的判断：
  · 失败的单位是**连接**不是请求（HTTP/2 会把几十个请求复用在那几条连接上）
    → 一条连接踩雷，它承载的整批资源全挂 —— 这正是"页面出来了但 panel.html 报无法连接"。
  · 因此最有效的不是"减少请求数"，而是**失败就重试**（= 重新掷骰子，命中好机房概率高）。
  · 开场影片是按**时间**结束的、任意点击可跳过，所以它**不是**"按钮不出现"的原因
    （这点我之前判断错了）；它真正的问题是 **144 帧同时抢带宽**，把壳/主题 JS 饿死。

改动：
  1. sw.js：新增 fetchRetry()，所有网络取数最多 3 次（间隔 300/800ms，4xx 不重试），
     install 的 51 个壳文件同样带重试；导航/清单走 networkFirst+重试→回退缓存。
     —— 这是对"逐连接掷骰子"最直接的修复。
  2. sw.js：/cdn-cgi/* 永不缓存（此前被当普通静态资源缓存：诊断页会显示旧机房，
     人机验证脚本被缓存会导致验证失败）。
  3. shim：开场影片帧**限流到 2 并发**（此前走浏览器默认的 6 并发，把首屏带宽吃光）。
     ⚠️ 首版正则写成 /\/assets\/intro\//，而主题传进来 norm() 后是 `assets/intro/…`（无前导斜杠）
     → 完全没匹配上、限流等于没做（实测峰值并发仍是 6）。改成 /assets[\\/]intro[\\/]/i。
  4. app.js：后台预取改为**等开场影片结束**（boot-end）后再开始，20 秒兜底。

