菜单细节修复：空的原生菜单不再显示、子菜单不再"没碰到就消失"、界面语言各面板一致

用户实测两个问题：
① 打开 MENU 后悬停 File/Edit/View/Playback/Library/Help，每个选项左上角出现一个小灰框
② 移到 Audio Archive 上出现的子菜单，鼠标还没碰上去就消失了

① 的成因：这六项是 **foobar2000 的原生主菜单**（header.js:328 用
   fb.CreateMainMenuManager().BuildMenu 填充），网页版没有对应命令 → 它们是空菜单。
   照原样渲染就成了"悬停出现一个小灰框"。现在空子菜单整行不渲染，
   并清掉因此暴露出来的开头/结尾/连续分隔线（主题在原生菜单后加的那条会变成孤线）。

② 的成因：子菜单在行的 mouseleave 里被**立刻**删除，指针从父行移向子菜单要跨几像素
   缝隙，还没碰到就没了；而且主菜单贴右边、子菜单在右侧放不下会翻到左侧，
   手感方向相反更容易触发。现在改成**延迟 260ms 关闭**：指针进入子菜单即取消，
   定时器整棵菜单树共用，所以跨层级也成立（父行 → 子菜单 → 它的子菜单）。

顺带修掉一个只有多面板才会暴露的设置竞争：
   主题的设置是"读整份 → 改一个键 → 覆盖整份写回"（lib/settings.js:26-32），
   而十个面板会同时这么干 → 后写的把别人刚加的键覆盖掉。实测丢过 uiLang：
   文件里没有它之后 getSetting 会回退到 window.GetProperty（**每个面板各自一份**），
   于是出现"header 面板英文、其它面板中文"这种同一界面语言不一致的怪象。
   shim 的 WriteTextFile 现在对设置文件做按键合并（主题只设键、从不删键，合并安全）。

