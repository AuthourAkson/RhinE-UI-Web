#!/usr/bin/env bash
set -u
cd /d/AgentTestLab/RhinE-UI || exit 1
rm -f .dev/orig-mili-wave.json          # 拟合用的原版数据，不进仓库
grep -q 'orig-\*.json' .gitignore || printf '\n# 拟合原版用的临时数据（原版缓存副本）\n.dev/orig-*.json\n' >> .gitignore
git add -A
git commit -q -F - <<'MSG'
波形轨迹取值再调：(峰值×RMS)^0.65，起伏与原版一致（CV 0.244）

上一版用 √(峰值×RMS)。用户拿原版与网页版的轨迹截图对比后指出幅度起伏仍不如原版，
于是把两张截图做了同口径测量（条高分布 / 变异系数 / 有内容的列占比 / 条距）：

              变异系数 ↓   有内容列占比
  原版          0.172        74.5%
  上一版        0.140 ✗      55.2% ✗

关键认识：主题会按最大值归一化，所以**绝对大小不影响画面**，只有形状（CV + 相关性）决定观感。
于是拿原版自己缓存里**同一首歌**的 1024 个真值（CV = 0.244）重新拟合：

  算法              CV      相关      （目标 CV 0.244）
  纯峰值           0.191    0.8435
  pure RMS         0.258    0.8909
  √(峰值×RMS)      0.215    0.9118
  (峰值×RMS)^0.65  0.244 ✓  0.909 ✓   ← 采用

修复后同一首：CV = 0.244（与原版完全一致）、>0.9 饱和占比 40.5% → 14.4%
（留足动态余量，起伏比原版更清楚而不糊成一片）、开头 77,741,326,748… 与原版 74,492,382,551…
同一升降节奏。

另外记一个**无法完全消除的差异**：条距。原版是原生 D2D，dp() 直接落在设备像素上
（150% 下 step=4 设备像素、条宽 3 → 有内容列 74.5%）；网页版画布按 CSS px + DPR 变换绘制，
dp(2.7)=3 CSS px ×1.5 = 4.5 设备像素、条宽 3 → 有内容列 ~55%，即同样宽度下条数略少、间隙略宽。
要完全一致就得让 dp() 落在设备像素网格上，而那等于让整套 UI 按 1.5 倍版式重排
（之前试过并被否定：所有元素等比放大会互相挤压错位）。所以保留现状并在此记录。
MSG
echo "已提交："; git log --oneline -1
